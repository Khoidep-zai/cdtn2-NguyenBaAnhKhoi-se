def main():
    print(f"Reading existing dataset from {DATASET_CSV}...")
    df_old = pd.read_csv(DATASET_CSV)
    print(f"Initial total rows: {len(df_old)}")

    # Check if already appended
    existing_ids = set(df_old["job_id"].astype(str))
    to_add = [j for j in NEW_HCM_JOBS if j["job_id"] not in existing_ids]

    if not to_add:
        print("All 20 new jobs are already present in the dataset.")
        return

    df_new = pd.DataFrame(to_add)
    df_combined = pd.concat([df_old, df_new], ignore_index=True)

    print(f"Saving updated dataset with {len(df_combined)} rows to {DATASET_CSV}...")
    df_combined.to_csv(DATASET_CSV, index=False, encoding="utf-8-sig")
    print(f"✅ Successfully appended {len(to_add)} new jobs in Ho Chi Minh City! Total rows: {len(df_combined)}")

